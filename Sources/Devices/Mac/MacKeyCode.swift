import BaguetteDevice
import Foundation

/// The Mac's own virtual key codes (`kVK_*` in Carbon's Events.h) — what a
/// keyboard `CGEvent` takes — for baguette's keyboard keys (by HID usage,
/// page 7) and modifiers. Nil for what the Mac has no key for. The ANSI codes
/// follow the physical layout, not the alphabet, so the table is by hand.
enum MacKeyCode {
    static func of(usage: UInt32) -> UInt16? {
        switch usage {
        case 0x04...0x1D: letters[Int(usage - 0x04)]
        case 0x1E...0x27: digits[Int(usage - 0x1E)]
        default: named[usage]
        }
    }

    static func of(_ modifier: KeyModifier) -> UInt16 {
        switch modifier {
        case .command: 0x37
        case .shift: 0x38
        case .option: 0x3A
        case .control: 0x3B
        }
    }

    /// a … z.
    private static let letters: [UInt16] = [
        0x00, 0x0B, 0x08, 0x02, 0x0E, 0x03, 0x05, 0x04, 0x22, 0x26, 0x28, 0x25, 0x2E,
        0x2D, 0x1F, 0x23, 0x0C, 0x0F, 0x01, 0x11, 0x20, 0x09, 0x0D, 0x07, 0x10, 0x06,
    ]

    /// 1 … 9, then 0.
    private static let digits: [UInt16] = [0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1A, 0x1C, 0x19, 0x1D]

    private static let named: [UInt32: UInt16] = [
        0x28: 0x24, 0x29: 0x35, 0x2A: 0x33, 0x2B: 0x30, 0x2C: 0x31,  // return, escape, delete, tab, space
        0x2D: 0x1B, 0x2E: 0x18, 0x2F: 0x21, 0x30: 0x1E, 0x31: 0x2A,  // - = [ ] \
        0x33: 0x29, 0x34: 0x27, 0x35: 0x32, 0x36: 0x2B, 0x37: 0x2F,  // ; ' ` , .
        0x38: 0x2C,                                                  // /
        0x4F: 0x7C, 0x50: 0x7B, 0x51: 0x7D, 0x52: 0x7E,              // → ← ↓ ↑
        0x54: 0x4B, 0x55: 0x43, 0x56: 0x4E, 0x57: 0x45, 0x58: 0x4C,  // keypad / * - + enter
        0x59: 0x53, 0x5A: 0x54, 0x5B: 0x55, 0x5C: 0x56, 0x5D: 0x57,  // keypad 1–5
        0x5E: 0x58, 0x5F: 0x59, 0x60: 0x5B, 0x61: 0x5C, 0x62: 0x52,  // keypad 6–9, 0
        0x63: 0x41, 0x67: 0x51,                                      // keypad . =
    ]
}
